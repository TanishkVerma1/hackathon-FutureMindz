import { test, expect } from '@playwright/test';
import fs from 'node:fs';

const screenshots = '.local-data/screenshots';
fs.mkdirSync(screenshots, { recursive: true });

test('offline dashboard, local OCR, difficult-case correction, approval and held edits', async ({ page }) => {
  const external = [];
  const errors = [];
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:3101') && !request.url().startsWith('data:') && !request.url().startsWith('blob:')) external.push(request.url()); });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Evidence first. Listings second.' })).toBeVisible();
  await expect(page.locator('.stock-table tbody tr')).toHaveCount(10);
  await page.screenshot({ path: `${screenshots}/dashboard.png`, fullPage: true });
  await page.getByRole('button', { name: 'Open workspace: DEMO-02', exact: true }).click();
  await expect(page.getByText('The evidence disagrees. We do not guess.')).toBeVisible();
  await expect(page.getByText('Donor year: 2017 vs 2018')).toBeVisible();
  await page.screenshot({ path: `${screenshots}/difficult-case.png`, fullPage: true });
  await page.getByRole('button', { name: 'Run local OCR', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Local OCR result', exact: true })).toBeVisible({ timeout: 35000 });
  await expect(page.locator('.ocr-result pre')).toContainText('DEMO-02');
  await page.getByRole('button', { name: 'Resolve conflict' }).click();
  await expect(page.locator('.field-form')).toBeVisible();
  await page.locator('.field-form input[type=number]').fill('2018');
  await page.locator('.field-form textarea').fill('Checked fictional dismantling note: donor year 2018');
  await page.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(page.locator('.conflict-banner')).toHaveCount(0);
  for (const [label, value] of [['Condition / defects', 'Broken mounting tab, seller confirmed'], ['Packaged weight (kg)', '2']]) {
    await page.getByRole('button', { name: `Edit ${label}`, exact: true }).click();
    const input = page.locator('.field-form input').first();
    await input.fill(value);
    await page.locator('.field-form textarea').fill('Physical fixture inspection, confirmed by seller');
    await page.getByRole('button', { name: 'Save correction', exact: true }).click();
    await expect(page.locator('.field-form')).toHaveCount(0);
  }
  await page.getByRole('button', { name: 'Edit Testing status', exact: true }).click();
  await page.locator('.field-form select').selectOption('untested');
  await page.locator('.field-form textarea').fill('Confirmed no electrical testing performed on this fictional fixture');
  await page.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(page.locator('.workspace-status .badge')).toContainText('Ready for seller review');
  await page.getByRole('tab', { name: 'Listing draft', exact: true }).click();
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue(/Broken mounting tab/);
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue(/2018/);
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue(/Compatibility remains unverified/);
  await page.locator('.approval-panel input[type=checkbox]').check();
  await page.getByRole('button', { name: 'Approve local draft', exact: true }).click();
  await expect(page.getByText('Seller approved this revision', { exact: true })).toBeVisible();
  await page.getByLabel('Description', { exact: true }).fill('Looks perfect. Fully functional and guaranteed fit.');
  await page.getByRole('button', { name: 'Save and validate', exact: true }).click();
  await expect(page.getByText('Unvalidated edits are held', { exact: true })).toBeVisible();
  await expect(page.getByText('Prior approval invalidated by changes', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Approve local draft', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Restore evidence template', exact: true }).click();
  await expect(page.getByText('Unvalidated edits are held', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: `${screenshots}/listing-draft.png`, fullPage: true });
  expect(external).toEqual([]);
  expect(errors).toEqual([]);
});

test('import preview, measured-results empty state, database, Arabic and mobile layouts', async ({ page }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#import');
  await page.locator('input[type=file]').setInputFiles({ name: 'test.csv', mimeType: 'text/csv', buffer: Buffer.from('stock_id,part_type,part_number\nBROWSER-CSV-01,Side-view mirror,00123\n') });
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Preview CSV', exact: true }).click();
  await expect(page.locator('.preview-table')).toContainText('00123');
  await page.goto('/#evaluation');
  await expect(page.getByRole('heading', { name: 'The case-study judging framework' })).toBeVisible();
  await expect(page.locator('.rubric-item')).toHaveCount(5);
  await expect(page.locator('.evaluation-summary')).toContainText('Not measured');
  await page.goto('/#database');
  await expect(page.getByRole('heading', { name: 'Your data stays here.' })).toBeVisible();
  await expect(page.getByText('evaluation_measurements', { exact: true })).toBeVisible();
  await page.goto('/');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(page.getByRole('heading', { name: 'الأدلة أولاً، ثم القوائم.' })).toBeVisible();
  await page.screenshot({ path: `${screenshots}/arabic.png`, fullPage: true });
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('button', { name: 'Toggle color theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: `${screenshots}/dark.png`, fullPage: true });
  await page.getByRole('button', { name: 'Toggle color theme' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${screenshots}/mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
